<?php
// Convert a Google service-account key JSON into Php/Private/ServiceAccount.php, the form App.php loads
// through config 'serviceAccountPath' (a .php file that returns the JSON text, so the key is never servable).
// Usage:
//   php Php/Tools/MakeServiceAccountPhp.php <service-account.json>                       (writes to STDOUT)
//   php Php/Tools/MakeServiceAccountPhp.php <service-account.json> --out <path> [--force] (writes a file)
// Exit codes: 0 = success, 1 = invalid key file, 2 = usage error, 3 = output file problem.
// The key itself is never echoed anywhere except the generated PHP source.
declare(strict_types=1);

// Print a message to STDERR and terminate with the given exit code
function fail(string $message, int $code): never
{
    // Write the error to STDERR so STDOUT stays clean for redirection
    fwrite(STDERR, 'MakeServiceAccountPhp: ' . $message . "\n");
    // Stop with a non-zero status
    exit($code);
}

// Usage text shown on argument errors
$usage = 'usage: php Php/Tools/MakeServiceAccountPhp.php <service-account.json> [--out <path> [--force]]';

// Parse the command-line arguments (positional input, optional --out and --force)
$inputPath = null;
$outPath = null;
$force = false;
// Skip argv[0] (the script name) and walk the remaining arguments
$args = array_slice($argv, 1);
for ($i = 0; $i < count($args); $i++) {
    $arg = $args[$i];
    if ($arg === '--force') {
        // Allow replacing an existing output file
        $force = true;
    } elseif ($arg === '--out') {
        // The next argument is the output path; it must exist
        if (!isset($args[$i + 1]) || $args[$i + 1] === '') {
            fail('--out needs a path. ' . $usage, 2);
        }
        $outPath = $args[++$i];
    } elseif (str_starts_with($arg, '--out=')) {
        // Accept the --out=<path> spelling as well
        $outPath = substr($arg, strlen('--out='));
    } elseif ($arg === '-h' || $arg === '--help') {
        // Print usage to STDOUT and exit successfully
        fwrite(STDOUT, $usage . "\n");
        exit(0);
    } elseif (str_starts_with($arg, '--')) {
        // Unknown option
        fail('unknown option ' . $arg . '. ' . $usage, 2);
    } elseif ($inputPath === null) {
        // First positional argument is the key JSON
        $inputPath = $arg;
    } else {
        // More than one positional argument is a mistake
        fail('too many arguments. ' . $usage, 2);
    }
}
// The input path is mandatory
if ($inputPath === null || $inputPath === '') {
    fail('missing <service-account.json>. ' . $usage, 2);
}
// --force only makes sense together with --out
if ($force && $outPath === null) {
    fail('--force requires --out. ' . $usage, 2);
}

// The input must be an existing readable file
if (!is_file($inputPath) || !is_readable($inputPath)) {
    fail('cannot read ' . $inputPath, 1);
}
// Read the raw JSON text exactly as it is (this text is what App.php will json_decode)
$json = file_get_contents($inputPath);
if ($json === false) {
    fail('cannot read ' . $inputPath, 1);
}
// Strip a UTF-8 BOM, which json_decode would reject
if (str_starts_with($json, "\xEF\xBB\xBF")) {
    $json = substr($json, 3);
}

// Decode to validate; App.php decodes with assoc=true, so do the same here
$key = json_decode($json, true);
if (!is_array($key)) {
    fail('not valid JSON: ' . json_last_error_msg(), 1);
}
// Must be a service-account key, not an OAuth client or other credential file
if (($key['type'] ?? null) !== 'service_account') {
    fail('"type" is not "service_account"', 1);
}
// The fields App.php needs to sign its JWT must be non-empty strings
foreach (['client_email', 'private_key'] as $field) {
    if (!isset($key[$field]) || !is_string($key[$field]) || trim($key[$field]) === '') {
        fail('missing "' . $field . '"', 1);
    }
}
// A private key that is not PEM would only fail later at request time: reject it now
if (!str_contains($key['private_key'], '-----BEGIN') || !str_contains($key['private_key'], 'PRIVATE KEY-----')) {
    fail('"private_key" is not a PEM private key', 1);
}

// Escape for a single-quoted PHP string literal: backslashes first, then single quotes
$escaped = str_replace(['\\', "'"], ['\\\\', "\\'"], $json);
// Build the generated file: it returns the JSON text and prints nothing
$php = "<?php\n"
    . "// Service-account key (generated by MakeServiceAccountPhp.php; never committed)\n"
    . "return '" . $escaped . "';\n";

// Without --out, write the PHP source to STDOUT and finish
if ($outPath === null) {
    fwrite(STDOUT, $php);
    exit(0);
}

// Refuse to replace an existing file unless --force was given
if (file_exists($outPath) && !$force) {
    fail($outPath . ' already exists (use --force to overwrite)', 3);
}
// Refuse to write over a directory
if (is_dir($outPath)) {
    fail($outPath . ' is a directory', 3);
}
// The parent directory must already exist (never create folders implicitly)
if (!is_dir(dirname($outPath))) {
    fail('directory does not exist: ' . dirname($outPath), 3);
}
// Write atomically: a temp file in the same directory, then rename over the target
$tmp = $outPath . '.tmp-' . bin2hex(random_bytes(6));
if (file_put_contents($tmp, $php, LOCK_EX) !== strlen($php)) {
    // Clean up a partial temp file before failing
    @unlink($tmp);
    fail('cannot write ' . $tmp, 3);
}
// Owner-only permissions where the platform supports them (no effect on Windows)
@chmod($tmp, 0600);
// Move the finished file into place
if (!@rename($tmp, $outPath)) {
    @unlink($tmp);
    fail('cannot write ' . $outPath, 3);
}
// Confirm on STDERR so STDOUT stays empty in --out mode
fwrite(STDERR, 'MakeServiceAccountPhp: wrote ' . $outPath . "\n");
exit(0);
